// Regenerates supabase/migrations/20260929000000_jurisdiction_boundaries.sql from the pinned geoBoundaries release.
//   curl -sSL -o /tmp/ind_adm1.geojson <SOURCE_URL below>
//   node supabase/scripts/build_jurisdictions_migration.mjs /tmp/ind_adm1.geojson
// Refuses any file whose sha256 differs from the pinned release, so the migration is reproducible byte for byte.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE_URL =
  "https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/IND/ADM1/geoBoundaries-IND-ADM1.geojson";
const SOURCE_SHA256 = "47aa0acb6f69868daee49143276f3ce323f18905ba7d38d0a86816b405028736";
// name / statutory_order_ref / tariff_version mirror packages/domain/src/pricing/index.ts (computeItemizedStatutoryFare).
const ZONES = [
  { zone: "DL", shapeISO: "IN-DL", name: "NCT of Delhi", ref: "Delhi Transport Dept Gazette Order F.No.19(13)/Tpt/Ops/2021" },
  { zone: "UP", shapeISO: "IN-UP", name: "Uttar Pradesh", ref: "Uttar Pradesh Motor Vehicles (Ambulance Tariff) Schedule 2024" },
];
const TARIFF_VERSION = "2026-04-01";

const raw = readFileSync(process.argv[2] ?? "");
const sha = createHash("sha256").update(raw).digest("hex");
if (sha !== SOURCE_SHA256) throw new Error(`sha256 mismatch: got ${sha}, pinned ${SOURCE_SHA256}`);
const features = JSON.parse(raw.toString("utf8")).features;

const rows = ZONES.map(({ zone, shapeISO, name, ref }) => {
  const matches = features.filter((f) => f.properties.shapeISO === shapeISO);
  if (matches.length !== 1) throw new Error(`${shapeISO}: expected 1 feature, found ${matches.length}`);
  const g = JSON.stringify(matches[0].geometry);
  return `  ('${zone}', '${name}',\n   extensions.st_multi(extensions.st_setsrid(extensions.st_geomfromgeojson($geo$${g}$geo$), 4326))::extensions.geography(MultiPolygon, 4326),\n   '${ref}', '${TARIFF_VERSION}')`;
});

const sql = `-- jurisdictions boundary data (DATA_AND_SYNC_SPECIFICATION.md 5.3.9, G-06 / R-12). Generated by
-- supabase/scripts/build_jurisdictions_migration.mjs; do not edit by hand.
--
-- Source:  geoBoundaries gbOpen IND ADM1 (State / Union Territory), release commit 9469f09
--          ${SOURCE_URL}
--          sha256 ${SOURCE_SHA256}
-- Origin:  DataMeet India community, Election Commission of India (boundary year 2011; the DL and UP boundaries are unchanged since)
-- License: Creative Commons Attribution 2.5 India (CC BY 2.5 IN). Attribution: DataMeet / geoBoundaries (wmgeolab).
-- CRS:     WGS 84 (EPSG:4326); coordinates copied verbatim from the source GeoJSON, full resolution.
-- Features: IN-DL (Delhi, Polygon, promoted to MultiPolygon) and IN-UP (Uttar Pradesh, MultiPolygon).

insert into public.jurisdictions (zone, name, boundary, statutory_order_ref, tariff_version) values
${rows.join(",\n")}
on conflict (zone) do update
  set name = excluded.name,
      boundary = excluded.boundary,
      statutory_order_ref = excluded.statutory_order_ref,
      tariff_version = excluded.tariff_version;
`;

writeFileSync(
  fileURLToPath(new URL("../migrations/20260929000000_jurisdiction_boundaries.sql", import.meta.url)),
  sql,
);
console.log(`wrote migration (${sql.length} bytes)`);
